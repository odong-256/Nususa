/**
 * Checks if a given student email or registration number is on the certified automatic qualification list.
 */
export function findAutoQualifiedStudent(identifier: string): QualifiedStudentEntry | undefined {
  if (!identifier) return undefined;
  const clean = identifier.trim().toLowerCase();
  return OFFICIAL_QUALIFIED_STUDENTS.find(s => {
    const sEmail = s.email.toLowerCase();
    const sAlt = s.alternateEmail?.toLowerCase();
    const sReg = s.registrationNumber.toLowerCase();
    return sEmail === clean || sAlt === clean || sReg === clean;
  });
}
